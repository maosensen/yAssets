//! The agent surface's data layer — one implementation, two façades.
//!
//! Both the REST routes (`super::routes`) and the MCP tools (`super::mcp`) call
//! these functions, so the two can never drift apart. Everything reuses the
//! command cores (`commands::assets::list_page`, `commands::folders::all_folders_in`,
//! …) rather than hand-rolling SQL — an agent sees exactly what the UI sees.

use std::collections::HashMap;

use tauri::Manager;

