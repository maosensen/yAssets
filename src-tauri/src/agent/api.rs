pub async fn folder_stats<R: tauri::Runtime>(
    app: &tauri::AppHandle<R>,
    folder_id: &str,
) -> AppResult<FolderStatsRow> {
    let lib = library(app)?;
    let folder_id = folder_id.to_string();
    lib.read(move |conn| {
        // The command reports zeroes for an unknown id; an agent needs to know
        // it aimed at nothing, so confirm the folder exists first.
        let exists: bool = conn.query_row(
            "SELECT EXISTS (SELECT 1 FROM folders WHERE id = ?1)",
            [folder_id.as_str()],
            |row| row.get(0),
        )?;
        if !exists {
            return Err(AppError::NotFound(format!("folder {folder_id}")));
        }
        Ok(FolderStatsRow::from(
            crate::commands::folders::compute_folder_stats(conn, &folder_id)?,
        ))
    })
    .await
}

