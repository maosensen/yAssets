pub async fn similar<R: tauri::Runtime>(
    app: &tauri::AppHandle<R>,
    id: &str,
    max_distance: u32,
) -> AppResult<Vec<AssetRow>> {
    let lib = library(app)?;
    let id = id.to_string();
    let max_distance = max_distance.min(crate::commands::assets::MAX_SIMILAR_DISTANCE);
    lib.read(move |conn| {
        Ok(
            crate::commands::assets::similar_in(conn, &id, max_distance)?
                .into_iter()
                .map(AssetRow::from_summary)
                .collect(),
        )
    })
    .await
}

