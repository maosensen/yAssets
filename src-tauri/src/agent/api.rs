/// A full-library duplicate scan is O(n²) over fingerprints. Cheap enough to
/// offer, expensive enough that an agent in a retry loop shouldn't be able to
/// pin a core. Enforced here rather than in the route so the MCP tool is bound
/// by the same window.
pub const DUPLICATE_SCAN_INTERVAL: std::time::Duration = std::time::Duration::from_secs(30);
static LAST_DUPLICATE_SCAN: std::sync::Mutex<Option<std::time::Instant>> =
    std::sync::Mutex::new(None);

fn claim_duplicate_scan() -> AppResult<()> {
    let mut last = match LAST_DUPLICATE_SCAN.lock() {
        Ok(guard) => guard,
        Err(poisoned) => poisoned.into_inner(),
    };
    let now = std::time::Instant::now();
    if let Some(previous) = *last {
        if now.duration_since(previous) < DUPLICATE_SCAN_INTERVAL {
            return Err(AppError::RateLimited(format!(
                "a duplicate scan runs at most once every {}s",
                DUPLICATE_SCAN_INTERVAL.as_secs()
            )));
        }
    }
    *last = Some(now);
    Ok(())
}

pub async fn duplicates<R: tauri::Runtime>(
    app: &tauri::AppHandle<R>,
) -> AppResult<DuplicatesResponse> {
    let lib = library(app)?;
    claim_duplicate_scan()?;
    lib.read(|conn| {
        let scan = crate::commands::duplicates::scan_duplicates_in(conn)?;
        let map = |groups: Vec<Vec<crate::commands::assets::AssetSummary>>| {
            groups
                .into_iter()
                .map(|group| group.into_iter().map(AssetRow::from_summary).collect())
                .collect()
        };
        Ok(DuplicatesResponse {
            exact: map(scan.exact),
            visual: map(scan.visual),
        })
    })
    .await
}

/// The cached WebP thumbnail. Preferred over `file_bytes` for "what is this?"
/// questions: already downscaled, always the same format, a few KB.
pub async fn thumb_bytes<R: tauri::Runtime>(
    app: &tauri::AppHandle<R>,
    id: &str,
) -> AppResult<Vec<u8>> {
    if !is_valid_id(id) {
        return Err(AppError::NotFound(format!("asset {id}")));
    }
    let lib = library(app)?;
    let path = lib.thumb_path(id);
    tokio::fs::read(&path)
        .await
        .map_err(|_| AppError::NotFound(format!("no thumbnail for asset {id}")))
}

/// The managed original, with its recorded MIME type. Refuses anything over
/// [`MAX_FILE_BYTES`] instead of streaming it into a model's context.
pub async fn file_bytes<R: tauri::Runtime>(
    app: &tauri::AppHandle<R>,
    id: &str,
) -> AppResult<(Vec<u8>, String)> {
    if !is_valid_id(id) {
        return Err(AppError::NotFound(format!("asset {id}")));
    }
    let lib = library(app)?;
    let lookup = lib.clone();
    let asset_id = id.to_string();
    let (rel_path, mime, size) = lookup
        .read(move |conn| {
            conn.query_row(
                "SELECT rel_path, mime, size FROM assets WHERE id = ?1",
                [asset_id.as_str()],
                |row| {
                    Ok((
                        row.get::<_, String>(0)?,
                        row.get::<_, Option<String>>(1)?,
                        row.get::<_, i64>(2)?,
                    ))
                },
            )
            .map_err(|err| match err {
                rusqlite::Error::QueryReturnedNoRows => {
                    AppError::NotFound(format!("asset {asset_id}"))
                }
                other => other.into(),
            })
        })
        .await?;
    if size as u64 > MAX_FILE_BYTES {
        return Err(AppError::Conflict(format!(
            "asset is {size} bytes, over the {MAX_FILE_BYTES}-byte limit — \
             fetch its thumbnail instead"
        )));
    }
    let bytes = tokio::fs::read(lib.resolve_rel(&rel_path))
        .await
        .map_err(|_| AppError::NotFound(format!("file missing for asset {id}")))?;
    Ok((
        bytes,
        mime.unwrap_or_else(|| "application/octet-stream".into()),
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn only_generated_ids_are_accepted() {
        assert!(is_valid_id("asset000000000000001"));
        assert!(!is_valid_id("short"));
        assert!(!is_valid_id("../../../etc/passwd"));
        assert!(
            !is_valid_id("ASSET000000000000001"),
            "uppercase is not ours"
        );
        assert!(!is_valid_id("asset-0000000000001"), "no punctuation");
        assert!(!is_valid_id(&"a".repeat(33)));
    }
}
